/**
 * The web export's routes for a file server that is not Expo's (docs/24 §68): a file that exists wins, then the
 * dynamic pages most specific first, then the not-found page with a 404 — and the rules come from the export's files.
 *
 * Run directly with Node (type-stripping):
 *   node lib/web-routes.test.ts
 * Exits non-zero on any failure.
 */
import assert from 'node:assert/strict';
import { caddyRoutes, pageRoutes } from './web-routes.ts';

let passed = 0;
const it = (name: string, fn: () => void) => {
  fn();
  passed++;
  console.log('  ok  ' + name);
};

const EXPORT = [
  'index.html',
  'login.html',
  '(auth)/login.html',
  '(tabs)/inventory.html',
  'sales/index.html',
  'sales/period.html',
  'sales/[id].html',
  'sales/pay/[id].html',
  'agent/[id].html',
  'agent/providers.html',
  'agent/providers/[id].html',
  'unit/[identifier].html',
  'docs/[...rest].html',
  '+not-found.html',
  '_sitemap.html',
];

const match = (path: string) => pageRoutes(EXPORT).find((r) => new RegExp(r.pattern).test(path))?.page ?? null;

it('a fixed page needs no rule — the file is found by name — and the export’s own pages get none', () => {
  const pages = pageRoutes(EXPORT).map((r) => r.page);
  for (const fixed of ['/index.html', '/login.html', '/(auth)/login.html', '/sales/period.html', '/agent/providers.html', '/+not-found.html', '/_sitemap.html']) {
    assert.ok(!pages.includes(fixed), fixed);
  }
});

it('a page only inside a route group is reached at its visible path', () => {
  assert.equal(match('/inventory'), '/(tabs)/inventory.html');
});

it('every dynamic page answers its path, a reload or a bookmark included', () => {
  assert.equal(match('/sales/7d3f2a'), '/sales/[id].html');
  assert.equal(match('/sales/7d3f2a/'), '/sales/[id].html');
  assert.equal(match('/sales/pay/7d3f2a'), '/sales/pay/[id].html');
  assert.equal(match('/agent/providers/9'), '/agent/providers/[id].html');
  assert.equal(match('/agent/9'), '/agent/[id].html');
  assert.equal(match('/unit/356938035643809'), '/unit/[identifier].html');
  assert.equal(match('/docs/a/b/c'), '/docs/[...rest].html');
});

it('nothing else: an unknown path, a deeper path or a missing segment matches no rule (the not-found page answers)', () => {
  for (const path of ['/nope', '/sales/1/2/3', '/agent/providers/9/x', '/unit', '/sales/', '/']) assert.equal(match(path), null, path);
});

it('most specific first: more fixed segments, then more segments, the catch-all last', () => {
  const order = pageRoutes(EXPORT).map((r) => r.page);
  assert.ok(order.indexOf('/agent/providers/[id].html') < order.indexOf('/agent/[id].html'));
  assert.ok(order.indexOf('/sales/pay/[id].html') < order.indexOf('/sales/[id].html'));
  assert.equal(order[order.length - 1], '/docs/[...rest].html');
});

it('the Caddy fragment: one route, the file first, each page in order, then the not-found page with a 404', () => {
  const routes = pageRoutes(EXPORT);
  const caddy = caddyRoutes(routes);
  assert.match(caddy, /^# Generated by erp-mobile/);
  const file = caddy.indexOf('@file file {path} {path}.html {path}/index.html');
  const notFound = caddy.indexOf('rewrite * /+not-found.html');
  assert.ok(file > 0 && notFound > file);
  let last = file;
  for (const r of routes) {
    const at = caddy.indexOf(`rewrite * "${r.page}"`);
    assert.ok(at > last, r.page);
    last = at;
  }
  assert.ok(notFound > last);
  assert.match(caddy, /status 404/);
  // A path pattern is quoted whole: its backslashes and brackets reach Caddy unchanged.
  assert.match(caddy, /path_regexp "\^\/agent\/providers\/\[\^\/\]\+\/\?\$"/);
});

console.log('\n' + passed + ' passed');
