// Imports the owner's approved logo pack (Dukan-ERP-Logo-Pack, 2026-11-04) as the source of truth: no path is redrawn.
//   node scripts/brand/import-pack.cjs "<pack folder>"
// - copies the pack's opaque home icon PNG as the app icon, and its transparent D-symbol PNG as the dark splash image;
// - extracts every SVG's paths (with their fills and group offsets) into lib/brand-pack.ts for the app to draw;
// - writes the light-mode variant of each SVG by changing only the lettering colour (#FFFFFF → launch navy #000A37,
//   owner's instruction: the same artwork, other colours, on light), and rasterises the light D-symbol for the splash.
const fs = require('node:fs');
const path = require('node:path');

const PACK = process.argv[2];
if (!PACK || !fs.existsSync(path.join(PACK, 'README.txt'))) throw new Error('usage: node scripts/brand/import-pack.cjs "<Dukan-ERP-Logo-Pack folder>"');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'assets', 'brand', 'pack');
const LIGHT_LETTERING = '#000A37';

function parse(file) {
  const svg = fs.readFileSync(path.join(PACK, file), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const layers = [];
  // Every path, with the translate of the group it sits in (the pack uses `translate(x 0)` groups only).
  const re = /<g transform="translate\(([-\d.]+) ([-\d.]+)\)">|<\/g>|<path fill="(#[0-9A-Fa-f]{6})"( fill-rule="evenodd")? d="([^"]+)"\s*\/>/g;
  let offset = [0, 0];
  for (const m of svg.matchAll(re)) {
    if (m[1] !== undefined) offset = [Number(m[1]), Number(m[2])];
    else if (m[0] === '</g>') offset = [0, 0];
    else layers.push({ fill: m[3].toUpperCase(), evenOdd: !!m[4], d: m[5], dx: offset[0], dy: offset[1] });
  }
  if (layers.length === 0) throw new Error(`no path in ${file}`);
  return { viewBox, layers, svg };
}

fs.mkdirSync(OUT, { recursive: true });
const files = { icon: 'Icon/Home-icon.svg', symbol: 'Logo/D-symbol.svg', wordmark: 'Logo/DUKAN-ERP.svg', motionD: 'Motion/D.svg', motionUkan: 'Motion/UKAN.svg', motionErp: 'Motion/ERP.svg' };
const parsed = {};
for (const [key, file] of Object.entries(files)) {
  const p = parse(file);
  parsed[key] = { viewBox: p.viewBox, layers: p.layers };
  const base = path.basename(file, '.svg');
  fs.writeFileSync(path.join(OUT, `${base}.svg`), p.svg);
  if (key !== 'icon') fs.writeFileSync(path.join(OUT, `${base}-light.svg`), p.svg.replace(/fill="#FFFFFF"/gi, `fill="${LIGHT_LETTERING}"`));
}
fs.copyFileSync(path.join(PACK, 'README.txt'), path.join(OUT, 'README.txt'));
fs.copyFileSync(path.join(PACK, 'Motion', 'Replay.html'), path.join(OUT, 'Replay.html'));
fs.copyFileSync(path.join(PACK, 'Icon', 'Home-icon-1024.png'), path.join(ROOT, 'assets', 'images', 'icon.png'));
fs.copyFileSync(path.join(PACK, 'Logo', 'D-symbol-640.png'), path.join(ROOT, 'assets', 'images', 'splash-icon-dark.png'));

const ts = `/**
 * Generated by scripts/brand/import-pack.cjs from the owner's approved logo pack (Dukan-ERP-Logo-Pack, 2026-11-04).
 * Do not edit: re-import the pack. Paths are the pack's own; only the light variant's lettering colour differs.
 */
export const PACK_COLOURS = { accent: '#5146D9', launchNavy: '#000A37', iconNavy: '#0B1D59', lettering: '#FFFFFF', lightLettering: '${LIGHT_LETTERING}' } as const;

export interface PackLayer { readonly fill: string; readonly evenOdd: boolean; readonly d: string; readonly dx: number; readonly dy: number }
export interface PackArt { readonly viewBox: string; readonly layers: readonly PackLayer[] }

export const PACK: Record<'symbol' | 'wordmark' | 'motionD' | 'motionUkan' | 'motionErp', PackArt> = ${JSON.stringify(
  Object.fromEntries(Object.entries(parsed).filter(([k]) => k !== 'icon')),
  null,
  1,
)};
`;
fs.writeFileSync(path.join(ROOT, 'lib', 'brand-pack.ts'), ts);
console.log('imported', Object.keys(files).length, 'artworks');

// The light splash image: the pack's own D-symbol PNG, recoloured pixel by pixel. Each pixel lies on the line from the
// accent to the white lettering; it keeps its place on that line and its alpha, and only the white end moves to navy —
// so the accent and every anti-aliased edge are the pack's.
{
  const { PNG } = require('pngjs');
  const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
  const [accent, white, navy] = [hex('#5146D9'), hex('#FFFFFF'), hex(LIGHT_LETTERING)];
  const png = PNG.sync.read(fs.readFileSync(path.join(PACK, 'Logo', 'D-symbol-640.png')));
  const axis = white.map((w, i) => w - accent[i]);
  const len2 = axis.reduce((s, v) => s + v * v, 0);
  for (let i = 0; i < png.data.length; i += 4) {
    if (png.data[i + 3] === 0) continue;
    const c = [png.data[i], png.data[i + 1], png.data[i + 2]];
    const t = Math.max(0, Math.min(1, c.reduce((s, v, k) => s + (v - accent[k]) * axis[k], 0) / len2));
    for (let k = 0; k < 3; k++) png.data[i + k] = Math.round(accent[k] + t * (navy[k] - accent[k]));
  }
  fs.writeFileSync(path.join(ROOT, 'assets', 'images', 'splash-icon.png'), PNG.sync.write(png));
  console.log('light splash written', png.width, 'x', png.height);
}
