/**
 * Creating a business account, on the phone (restored 2026-10-13).
 *
 * The owner's decision of 2026-10-13 brings sign-up back into the app, where it
 * lived until 2026-10-05: a shop is set up by scanning stock, scanning happens
 * on the phone, and sending somebody elsewhere to type the longest form in the
 * product, then come back to do the real work, was never the shorter path. The
 * server answers it on `POST auth/register` and finishes it on
 * `auth/register/verify/*` — routes of the app's own authentication, never the
 * platform's.
 *
 * ## What this file is
 *
 * The rules, with no React and no network, so they can be tested directly. The
 * screen renders these decisions; it does not make them.
 *
 * ## What it deliberately does not collect
 *
 * No Store ID, company id, branch id, national or personal ID, role, permission
 * or subscription identifier. Every internal reference is generated by the
 * server. Asking somebody to invent or remember our identifiers is exactly how
 * the old sign-in became unusable — the type below is the guard: there is no
 * field to put one in.
 */

import type { Language } from './i18n';
import type { AcquisitionClaim } from './acquisition';
import { arabicNameHint, latinNameHint, type NameHint } from './display-name.ts';

export interface RegistrationDraft {
  ownerName: string;
  businessName: string;
  branchName: string;
  /** D225: each name in Arabic too — a new business, its first store and its Owner are created with both. */
  ownerNameAr: string;
  businessNameAr: string;
  branchNameAr: string;
  city: string;
  /** Optional (the owner's brief of 2026-10-18): verified later, from the account, if the Owner wants a second channel. */
  email: string;
  /** The WhatsApp number — required: the registration's code goes there, and so does every subscription message first. */
  phone: string;
  password: string;
  passwordConfirm: string;
  /**
   * The operational WhatsApp consent beside the number (D213): ticked by the person, never by default and never
   * because a number was typed. The server refuses a registration without it.
   */
  whatsappConsent: boolean;
}

export const emptyRegistration: RegistrationDraft = {
  ownerName: '',
  businessName: '',
  branchName: '',
  ownerNameAr: '',
  businessNameAr: '',
  branchNameAr: '',
  city: '',
  email: '',
  phone: '',
  password: '',
  passwordConfirm: '',
  whatsappConsent: false,
};

/** Which field a problem belongs to, so it can be shown beside its input. */
export type RegistrationField =
  | 'ownerName'
  | 'businessName'
  | 'branchName'
  | 'ownerNameAr'
  | 'businessNameAr'
  | 'branchNameAr'
  | 'email'
  | 'phone'
  | 'whatsappConsent'
  | 'password'
  | 'passwordConfirm';

/** A translation key, never a sentence — this module renders nothing. */
export type RegistrationProblems = Partial<Record<RegistrationField, string>>;

const NAME_HINT_KEY: Record<Exclude<NameHint, null>, string> = {
  latin_has_arabic: 'names.hint.latinHasArabic',
  latin_needs_letter: 'names.hint.latinNeedsLetter',
  arabic_needs_arabic: 'names.hint.arabicNeedsArabic',
};

/** Mirrors the server's `MinLength(8)`. Kept here only to fail fast, not to decide. */
export const MIN_PASSWORD = 8;

const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
/** Digits, optionally an international +. The server normalises properly. */
const PHONE = /^\+?[\d\s-]{6,24}$/;

/**
 * What is wrong with this draft, if anything.
 *
 * Returns keys rather than text so the same rules hold in all three languages,
 * and so a test can assert on a rule instead of on a sentence somebody may
 * reword later.
 */
export function validateRegistration(draft: RegistrationDraft): RegistrationProblems {
  const problems: RegistrationProblems = {};

  if (!draft.ownerName.trim()) problems.ownerName = 'register.problem.ownerName';
  if (!draft.businessName.trim()) problems.businessName = 'register.problem.businessName';
  if (!draft.branchName.trim()) problems.branchName = 'register.problem.branchName';
  // D225: each Latin name holds no Arabic letter, and each Arabic one at least one — the server's rule, said early.
  for (const field of ['ownerName', 'businessName', 'branchName'] as const) {
    const latin = latinNameHint(draft[field]);
    if (!problems[field] && latin) problems[field] = NAME_HINT_KEY[latin];
    const arabicField = `${field}Ar` as const;
    if (!draft[arabicField].trim()) problems[arabicField] = 'names.error.blank';
    else {
      const arabic = arabicNameHint(draft[arabicField]);
      if (arabic) problems[arabicField] = NAME_HINT_KEY[arabic];
    }
  }

  const email = draft.email.trim();
  const phone = draft.phone.trim();

  // The WhatsApp number is required (the owner's brief of 2026-10-18): it is
  // the contact the registration verifies and the credential the Owner signs
  // in with. The server refuses a registration without it too; catching it
  // here saves a round trip, it does not replace the rule. An email address is
  // optional, and checked only when given.
  if (!phone) problems.phone = 'register.problem.phoneRequired';
  else if (!PHONE.test(phone)) problems.phone = 'register.problem.phone';
  if (email && !EMAIL.test(email)) problems.email = 'register.problem.email';
  // The consent beside it (D213): the server refuses without it; asked here so nothing is sent for nothing.
  if (!draft.whatsappConsent) problems.whatsappConsent = 'register.problem.whatsappConsent';

  if (draft.password.length < MIN_PASSWORD) problems.password = 'register.problem.password';
  // Checked even when the password is too short: somebody fixing one error
  // should see both, not discover the second after fixing the first.
  if (draft.passwordConfirm !== draft.password) {
    problems.passwordConfirm = 'register.problem.passwordConfirm';
  }

  return problems;
}

/**
 * The exact body `POST auth/register` expects. Optional fields are omitted,
 * never empty. `language` is the one the person is reading, so the code the
 * server sends next arrives in it too. `consent` is what the ticked box agreed
 * to — the server's version and the language it was shown in — and is sent
 * only when the box is ticked (`consentFields`).
 */
export function registrationPayload(
  draft: RegistrationDraft,
  idempotencyKey: string,
  language: Language,
  consent: Record<string, string> = {},
  /** Where the business came from, if anywhere (0103): one promo code or one registration address, never both. */
  acquisition: AcquisitionClaim = null,
): Record<string, string> {
  const body: Record<string, string> = {
    idempotencyKey,
    ownerName: draft.ownerName.trim(),
    businessName: draft.businessName.trim(),
    branchName: draft.branchName.trim(),
    ownerNameAr: draft.ownerNameAr.trim(),
    businessNameAr: draft.businessNameAr.trim(),
    branchNameAr: draft.branchNameAr.trim(),
    phone: draft.phone.trim(),
    password: draft.password,
    language,
  };
  if (draft.city.trim()) body.city = draft.city.trim();
  if (draft.email.trim()) body.email = draft.email.trim();
  return { ...(draft.whatsappConsent ? { ...body, ...consent } : body), ...(acquisition ?? {}) };
}

/**
 * Whether two drafts make the same registration — the fields the server
 * receives, trimmed as it receives them.
 *
 * One idempotency key is one attempt. A retry of the same registration keeps
 * its key, so the second tap after a lost answer never creates a second
 * business. A registration edited after a failure is a new attempt with a new
 * key: the server answers a key it has already seen with the business it made
 * for it, whatever the body, so a corrected email would otherwise send the
 * code to the address the person had just corrected away from. The language is
 * not part of it — the code is sent by the code check, in the language on
 * screen then.
 */
export function sameRegistration(a: RegistrationDraft, b: RegistrationDraft): boolean {
  const x = registrationPayload(a, '', 'en');
  const y = registrationPayload(b, '', 'en');
  const fields = new Set([...Object.keys(x), ...Object.keys(y)]);
  return a.whatsappConsent === b.whatsappConsent && [...fields].every((field) => x[field] === y[field]);
}

/**
 * The form in three steps (owner's review, 2026-10-24): the business, the Owner, then how they sign in — the
 * number, its consent, an optional email address and the password. Presentation only: nothing is sent between steps,
 * and the one submission at the end is unchanged. City has no rule, so it appears in no step's list.
 */
export const REGISTRATION_STEPS: readonly (readonly RegistrationField[])[] = [
  ['businessName', 'businessNameAr', 'branchName', 'branchNameAr'],
  ['ownerName', 'ownerNameAr'],
  ['phone', 'whatsappConsent', 'email', 'password', 'passwordConfirm'],
];

/** The problems that belong to one step, in the order its fields appear. */
export function stepProblems(problems: RegistrationProblems, step: number): RegistrationProblems {
  const found: RegistrationProblems = {};
  for (const field of REGISTRATION_STEPS[step] ?? []) {
    if (problems[field]) found[field] = problems[field];
  }
  return found;
}

/** The first step holding a problem, or -1 — where a submission refused on the device takes the person back to. */
export function firstStepWithProblem(problems: RegistrationProblems): number {
  return REGISTRATION_STEPS.findIndex((fields) => fields.some((f) => problems[f]));
}
