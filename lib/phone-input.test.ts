import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { composePhone, countryName, countryOf, PHONE_COUNTRIES, splitPhone, typedInternational, countriesFor, searchCountries } from './phone-input.ts';

test('the default country gives the local number its code', () => {
  assert.equal(composePhone('MR', '22 12 34 56'), '+22222123456');
});

test('nothing typed is nothing sent', () => {
  assert.equal(composePhone('MR', '   '), '');
});

test('a chosen country, and its trunk zero dropped', () => {
  assert.equal(composePhone('FR', '06 12 34 56 78'), '+33612345678');
});

test('a number written whole keeps its own country', () => {
  assert.equal(composePhone('MR', '+33 6 12 34 56 78'), '+33612345678');
  assert.equal(composePhone('MR', '0033612345678'), '+33612345678');
  assert.equal(typedInternational(' +33'), true);
  assert.equal(typedInternational('22'), false);
});

test('Arabic-Indic digits are digits', () => {
  assert.equal(composePhone('MR', '٢٢١٢٣٤٥٦'), '+22222123456');
});

test('what is not a number is left for the form to refuse', () => {
  assert.equal(composePhone('MR', 'call me'), 'callme');
});

test('a stored number splits back, and round-trips', () => {
  for (const c of PHONE_COUNTRIES) {
    const stored = `+${c.code}12345678`;
    const { iso, national } = splitPhone(stored);
    assert.equal(composePhone(iso, national), stored);
  }
  assert.deepEqual(splitPhone('+22222123456'), { iso: 'MR', national: '22123456' });
});

test('a code not in the list is never guessed', () => {
  assert.deepEqual(splitPhone('+99912345678'), { iso: 'MR', national: '+99912345678' });
  assert.equal(composePhone('MR', '+99912345678'), '+99912345678');
});

test('every country is named in all three languages, with its own code', () => {
  // Every region libphonenumber-js dials (post-Build-4), each once; a code may be shared (+1, +7, +44).
  for (const language of ['en', 'fr', 'ar']) {
    for (const c of PHONE_COUNTRIES) assert.ok(countryName(c, language).length > 0);
  }
  assert.equal(countryOf('nowhere').iso, 'MR');
  assert.equal(new Set(PHONE_COUNTRIES.map((c) => c.iso)).size, PHONE_COUNTRIES.length);
  assert.ok(PHONE_COUNTRIES.length >= 240);
  assert.ok(PHONE_COUNTRIES.filter((c) => c.code === '1').length > 10);
});

test('the names are the maintained dataset’s, regenerated — never edited by hand', () => {
  const generated = readFileSync(new URL('./phone-country-names.ts', import.meta.url), 'utf8');
  assert.ok(generated.includes('Generated by scripts/phone/generate-country-names.cjs'));
  assert.equal(countryOf('FR').fr, 'France');
  assert.equal(countryOf('MR').ar, 'موريتانيا');
});

test('alphabetical in the reading language', () => {
  for (const language of ['en', 'fr', 'ar']) {
    const names = countriesFor(language).map((c) => countryName(c, language));
    const collator = new Intl.Collator(language, { sensitivity: 'base' });
    for (let i = 1; i < names.length; i++) assert.ok(collator.compare(names[i - 1]!, names[i]!) <= 0, `${language}: ${names[i - 1]} before ${names[i]}`);
  }
});

test('search: the reading language’s name, the English name, the ISO code, the calling code', () => {
  const fr = countriesFor('fr');
  assert.ok(searchCountries(fr, 'allem', 'fr').some((c) => c.iso === 'DE'));
  assert.ok(searchCountries(fr, 'germany', 'fr').some((c) => c.iso === 'DE'));
  assert.ok(searchCountries(fr, 'senegal', 'fr').some((c) => c.iso === 'SN'));
  assert.deepEqual(searchCountries(fr, 'mr', 'fr').map((c) => c.iso), ['MR']);
  assert.ok(searchCountries(fr, '+222', 'fr').some((c) => c.iso === 'MR'));
  assert.ok(searchCountries(fr, '00222', 'fr').some((c) => c.iso === 'MR'));
  const plusOne = searchCountries(fr, '+1', 'fr').filter((c) => c.code === '1').map((c) => c.iso);
  assert.ok(plusOne.includes('US') && plusOne.includes('CA') && plusOne.includes('JM'));
  assert.ok(searchCountries(countriesFor('ar'), 'موريت', 'ar').some((c) => c.iso === 'MR'));
});

test('a shared calling code: the number says which country; a pasted +code is never doubled', () => {
  assert.equal(splitPhone('+14165550123').iso, 'CA');
  assert.equal(splitPhone('+12025550123').iso, 'US');
  assert.equal(composePhone('US', '+1 416 555 0123'), '+14165550123');
  assert.equal(composePhone('MR', '+222 22 12 34 56'), '+22222123456');
  assert.equal(composePhone('MR', '(22) 12-34-56'), '+222221234 56'.replace(' ', ''));
});
