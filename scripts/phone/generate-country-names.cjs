// Writes lib/phone-country-names.ts from `i18n-iso-countries` (EN/FR/AR) for every region `libphonenumber-js` dials.
// Run after updating either package: node scripts/phone/generate-country-names.cjs
// `lib/phone-input.test.ts` fails when the file and the packages disagree, so it never drifts silently.
const fs = require('fs');
const path = require('path');
const countries = require('i18n-iso-countries');
for (const l of ['en', 'fr', 'ar']) countries.registerLocale(require(`i18n-iso-countries/langs/${l}.json`));
const { getCountries } = require('libphonenumber-js/min');
// Named here: the territories the names package lacks.
const NAMED_HERE = {
  AC: ['Ascension Island', 'Île de l’Ascension', 'جزيرة أسينشين'],
  TA: ['Tristan da Cunha', 'Tristan da Cunha', 'تريستان دا كونا'],
};
const rows = getCountries().map((iso) => {
  const names = ['en', 'fr', 'ar'].map((l, i) => countries.getName(iso, l) ?? NAMED_HERE[iso]?.[i]);
  if (names.some((n) => !n)) throw new Error(`No name for ${iso}`);
  return [iso, ...names];
});
const body = rows.map((r) => `  [${r.map((v) => JSON.stringify(v)).join(', ')}],`).join('\n');
const out = `/**
 * Generated by scripts/phone/generate-country-names.cjs from i18n-iso-countries ${require('i18n-iso-countries/package.json').version} and
 * libphonenumber-js ${require('libphonenumber-js/package.json').version}. Do not edit: regenerate.
 * [ISO, English, French, Arabic] for every region with a calling code.
 */
export const COUNTRY_NAMES: readonly (readonly [string, string, string, string])[] = [
${body}
];
`;
fs.writeFileSync(path.join(__dirname, '..', '..', 'lib', 'phone-country-names.ts'), out);
console.log(`${rows.length} regions`);
