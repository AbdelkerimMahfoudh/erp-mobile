/**
 * The web export's routes, for a server that is not Expo's own (docs/24 §68).
 *
 * `expo export --platform web` with static output writes one page per screen: `sales/period.html` for a fixed route,
 * `sales/[id].html` for a dynamic one, `(auth)/login.html` beside `login.html` for a route group. A plain file server
 * finds the first kind and none of the others, so `/sales/7d3f…` — a link, a reload, a bookmark — would answer "not
 * found". These rules close that gap, in the one order that is right: a file that exists always wins, then the
 * dynamic pages from the most fixed segments to the fewest, then the export's own not-found page with a 404.
 *
 * The rules are read from the export's files, never written by hand, so a new screen cannot be forgotten.
 */

export interface PageRoute {
  /** The path pattern, anchored: `^/sales/[^/]+/?$`. */
  pattern: string;
  /** The page that answers it, from the export's root: `/sales/[id].html`. */
  page: string;
}

const GROUP = /^\(.+\)$/;
const CATCH_ALL = /^\[\.\.\..+\]$/;
const PARAM = /^\[.+\]$/;

const escapeRegex = (s: string) => s.replace(/[.*+?^${}()|[\]\\/-]/g, '\\$&');

/**
 * The routes a file server cannot find by name, from the export's page paths (relative, `/`-separated).
 *
 * Fixed pages need no rule — the file is found — except a page that exists only inside a route group. Dynamic pages
 * are ordered most specific first: more fixed segments, then more segments, then a catch-all last.
 */
export function pageRoutes(pages: readonly string[]): PageRoute[] {
  const literal = new Set(pages);
  const routes: (PageRoute & { fixed: number; length: number; catchAll: boolean })[] = [];
  const seen = new Set<string>();

  for (const page of pages) {
    if (!page.endsWith('.html')) continue;
    const segments = page.slice(0, -'.html'.length).split('/');
    const inGroup = segments.some((s) => GROUP.test(s));
    const visible = segments.filter((s) => !GROUP.test(s));
    if (visible.length === 0 || visible.some((s) => s.startsWith('+') || s.startsWith('_'))) continue;
    // A fixed page outside a group is found by name; inside one, only when the same page is also exported outside it.
    if (!visible.some((s) => PARAM.test(s)) && (!inGroup || literal.has(`${visible.join('/')}.html`))) continue;
    if (visible[visible.length - 1] === 'index') visible.pop();

    const pattern = `^/${visible
      .map((s) => (CATCH_ALL.test(s) ? '.+' : PARAM.test(s) ? '[^/]+' : escapeRegex(s)))
      .join('/')}/?$`;
    if (seen.has(pattern)) continue;
    seen.add(pattern);
    routes.push({
      pattern,
      page: `/${page}`,
      fixed: visible.filter((s) => !PARAM.test(s)).length,
      length: visible.length,
      catchAll: visible.some((s) => CATCH_ALL.test(s)),
    });
  }

  return routes
    .sort((a, b) => Number(a.catchAll) - Number(b.catchAll) || b.fixed - a.fixed || b.length - a.length || a.page.localeCompare(b.page))
    .map(({ pattern, page }) => ({ pattern, page }));
}

/**
 * The same rules as a Caddyfile fragment, imported inside the site block that sets `root` (the staging edge,
 * erp-backend `deploy/staging/web-test.caddy`). One `route`, so its order is the order written here.
 */
export function caddyRoutes(routes: readonly PageRoute[]): string {
  const quote = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  const lines = [
    '# Generated by erp-mobile scripts/web-test-release.mjs from the export it sits beside. Do not edit.',
    'route {',
    '\t@file file {path} {path}.html {path}/index.html',
    '\thandle @file {',
    '\t\trewrite * {file_match.relative}',
    '\t\tfile_server',
    '\t}',
  ];
  routes.forEach((r, i) => {
    lines.push(`\t@page${i} path_regexp ${quote(r.pattern)}`, `\thandle @page${i} {`, `\t\trewrite * ${quote(r.page)}`, '\t\tfile_server', '\t}');
  });
  lines.push('\thandle {', '\t\trewrite * /+not-found.html', '\t\tfile_server {', '\t\t\tstatus 404', '\t\t}', '\t}', '}', '');
  return lines.join('\n');
}
